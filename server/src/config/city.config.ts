export const DEFAULT_CITY = INDIAN_CITIES[0]; // Pune default

export function getCityConfig(query?: string): CityConfig {
  if (!query) return DEFAULT_CITY;
  const normalized = query.trim().toLowerCase();
  
  const found = INDIAN_CITIES.find(
    (c) =>
      c.id.toLowerCase() === normalized ||
      c.name.toLowerCase() === normalized ||
      c.name.toLowerCase().includes(normalized)
  );

  if (found) return found;

  // Default fallback if not found in list
  return DEFAULT_CITY;
}

export function createDynamicCityConfig(
  name: string,
  state: string,
  lat: number,
  lng: number,
  bbox?: [number, number, number, number]
): CityConfig {
  const delta = 0.12; // roughly 12-15km bounding box
  const computedBbox: [number, number, number, number] = bbox || [
    Number((lat - delta).toFixed(4)),
    Number((lng - delta).toFixed(4)),
    Number((lat + delta).toFixed(4)),
    Number((lng + delta).toFixed(4)),
  ];

  return {
    id: name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    name,
    state: state || 'India',
    center: { lat, lng },
    bbox: computedBbox,
    defaultZoom: 13,
    popular: false,
  };
}
